export const BUILT_IN_SOUL_MAP: Record<string, SoulDefinition> = Object.fromEntries(
  BUILT_IN_SOULS.map((s) => [s.id, s]),
);

/**
 * Backward compatibility adapter: Maps legacy 6 archetype keys to new Soul definitions.
 */
export const LEGACY_ARCHETYPE_TO_SOUL_ID: Record<string, string> = {
  empath: 'soul_caregiver',
  mentor: 'soul_sage',
  tactical: 'soul_analyst',
  spark: 'soul_trickster',
  cynic: 'soul_rebel',
  visionary: 'soul_strategist',
};

export function getBuiltInSoul(id: string): SoulDefinition | null {
  if (BUILT_IN_SOUL_MAP[id]) return BUILT_IN_SOUL_MAP[id];
  const mapped = LEGACY_ARCHETYPE_TO_SOUL_ID[id];
  return mapped ? BUILT_IN_SOUL_MAP[mapped] ?? null : null;
}
